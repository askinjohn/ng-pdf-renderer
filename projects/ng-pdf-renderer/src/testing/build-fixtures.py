"""Generate local, synthetic browser-test PDFs; requires pypdf (not a runtime dependency)."""
from pathlib import Path
from base64 import b64encode
from io import BytesIO
from pypdf import PdfWriter
from pypdf.generic import DictionaryObject as D, NameObject as N, ArrayObject as A, NumberObject as I, TextStringObject as T, DecodedStreamObject

writer = PdfWriter()
page = writer.add_blank_page(300, 400)
second_page = writer.add_blank_page(300, 400)
font = writer._add_object(D({N('/Type'): N('/Font'), N('/Subtype'): N('/Type1'), N('/BaseFont'): N('/Helvetica')}))
resources = D({N('/Font'): D({N('/F1'): font})})
fields, annotations = A(), A()

def widget(ft, name, rect, value=None, flags=0, **extra):
    data = D({N('/Type'): N('/Annot'), N('/Subtype'): N('/Widget'), N('/FT'): N(ft), N('/T'): T(name), N('/TU'): T(name), N('/Rect'): A([I(n) for n in rect]), N('/F'): I(4), N('/Ff'): I(flags), N('/DA'): T('/F1 12 Tf 0 g'), N('/P'): page.indirect_reference})
    if value is not None: data[N('/V')] = value
    for key, val in extra.items(): data[N('/'+key)] = val
    ref = writer._add_object(data)
    fields.append(ref)
    annotations.append(ref)
    return data, ref

widget('/Tx', 'Full name', [30, 330, 230, 354], T('Before'))
widget('/Tx', 'Notes', [30, 255, 230, 315], T('Initial notes'), flags=4096)
widget('/Tx', 'Read only', [30, 220, 230, 244], T('Locked'), flags=1)

def appearance(checked):
    stream = DecodedStreamObject()
    stream.set_data(b'0 0 20 20 re S\n' + (b'0 0 m 20 20 l S\n' if checked else b''))
    stream.update({N('/Type'): N('/XObject'), N('/Subtype'): N('/Form'), N('/BBox'): A([I(0),I(0),I(20),I(20)]), N('/Resources'): D()})
    return writer._add_object(stream)

off, on = appearance(False), appearance(True)
widget('/Btn', 'Agree', [30, 180, 50, 200], N('/Off'), AP=D({N('/N'): D({N('/Off'): off,N('/Yes'): on})}), AS=N('/Off'))
widget('/Ch', 'Country', [70, 178, 230, 202], T('IN'), flags=131072, Opt=A([A([T('IN'),T('India')]),A([T('US'),T('United States')])]))
widget('/Ch', 'Topics', [30, 75, 230, 125], A([T('A')]), flags=2097152, Opt=A([T('A'),T('B'),T('C')]))
parent = D({N('/FT'):N('/Btn'),N('/T'):T('Plan'),N('/Ff'):I(32768),N('/V'):N('/First')})
parent_ref = writer._add_object(parent)
kids = A()
for index, name in enumerate(['First','Second']):
    child = D({N('/Type'):N('/Annot'),N('/Subtype'):N('/Widget'),N('/Parent'):parent_ref,N('/Rect'):A([I(30+index*40),I(140),I(50+index*40),I(160)]),N('/F'):I(4),N('/P'):page.indirect_reference,N('/AP'):D({N('/N'):D({N('/Off'):off,N('/'+name):on})}),N('/AS'):N('/First' if index==0 else '/Off')})
    ref=writer._add_object(child)
    kids.append(ref)
    annotations.append(ref)
parent[N('/Kids')]=kids
fields.append(parent_ref)
page[N('/Annots')]=annotations
writer._root_object[N('/AcroForm')]=writer._add_object(D({N('/Fields'):fields,N('/DR'):resources,N('/DA'):T('/F1 12 Tf 0 g')}))
# Supply real page content and appearance streams, as a normal fillable PDF would.
def page_content(target, lines):
    target[N('/Resources')] = resources
    content = DecodedStreamObject()
    commands = ['0.12 0.22 0.35 rg']
    for text, x, y, size in lines:
        commands.append(f'BT /F1 {size} Tf {x} {y} Td ({text}) Tj ET')
    content.set_data(('\n'.join(commands)).encode('ascii'))
    target[N('/Contents')] = writer._add_object(content)

