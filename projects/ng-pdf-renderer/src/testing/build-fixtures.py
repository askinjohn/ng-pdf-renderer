writer.update_page_form_field_values(page, {'Full name': 'Before', 'Notes': 'Initial notes', 'Read only': 'Locked', 'Country': 'IN', 'Topics': ['A']}, auto_regenerate=False)

root = writer.add_outline_item('Chapter one',0)
writer.add_outline_item('Details on page two',1,parent=root)

def encode(writer):
    output=BytesIO()
    writer.write(output)
    return b64encode(output.getvalue()).decode('ascii')
plain=encode(writer)
writer.encrypt('viewer-test', owner_password='fixture-owner', algorithm='RC4-128')
encrypted=encode(writer)
